// Composes brand/gov-face-cycle.svg from the gov emotion suite.
// Picks 8 states and stacks them as <g> layers with cross-fading CSS
// keyframes, producing a single self-contained animated SVG that works:
//
//   - inline in HTML
//   - in <img src=...> tags (GitHub README, anywhere SMIL/CSS-in-SVG works)
//   - at any size (uses viewBox)
//
//   node brand/build-face-cycle.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '..', 'emotions', 'gov_emotions', 'svgs');

// Friendly arc: neutral → weighing → approving → satisfied → loop.
const FRAMES = [
  'gov_01_default.svg',
  'gov_11_thinking.svg',
  'gov_05_sceptical.svg',
  'gov_09_confused.svg',
  'gov_18_pleased.svg',
  'gov_19_smiling.svg',
  'gov_20_cheeky.svg',
  'gov_06_smug.svg',
];

// Cycle duration in seconds. Each frame holds for total/N, with a small
// cross-fade between frames.
const TOTAL_S = 12;
const N = FRAMES.length;
const SLOT = 100 / N;          // % of cycle per frame
const FADE = 1.5;              // % cross-fade window

// Pull the inner markup out of each source SVG, stripping the wrapper
// <svg>...</svg> and the shared background <rect>. We only want the
// face features, since the background is drawn once for the whole cycle.
function featuresOf(file) {
  const raw = readFileSync(join(SRC, file), 'utf8');
  const inner = raw.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  return inner.replace(/<rect x="0" y="0" width="160" height="160" rx="6" fill="#1a1a1a"\/>/, '').trim();
}

// Class and keyframe names are prefixed `gov-` because <style> inside an
// inline SVG in HTML5 leaks into the global stylesheet; prefixed names
// avoid colliding with host-page CSS.
const PFX = 'gov-cyc';

function keyframesFor(i) {
  const start = i * SLOT;
  const fadeInEnd = start + FADE;
  const holdEnd = start + SLOT - FADE;
  const end = start + SLOT;
  const clamp = (p) => Math.max(0, Math.min(100, p)).toFixed(4);
  return `@keyframes ${PFX}-f${i}{` +
    (start > 0 ? `0%,${clamp(start)}%{opacity:0}` : '') +
    `${clamp(fadeInEnd)}%,${clamp(holdEnd)}%{opacity:1}` +
    `${clamp(end)}%,100%{opacity:0}` +
    `}`;
}

const layers = FRAMES.map((f, i) =>
  `<g class="${PFX}-frame" style="animation:${PFX}-f${i} ${TOTAL_S}s linear infinite">${featuresOf(f)}</g>`,
).join('');

const style =
  `<style>.${PFX}-frame{opacity:0}` +
  FRAMES.map((_, i) => keyframesFor(i)).join('') +
  // First frame visible (no animation) when the user has asked the OS to
  // reduce motion. Targeted via :nth-of-type since classes are shared.
  `@media (prefers-reduced-motion:reduce){.${PFX}-frame{animation:none!important;opacity:0}` +
  `.${PFX}-frame:first-of-type{opacity:1}}` +
  `</style>`;

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 160" role="img" aria-label="Governor">` +
  style +
  `<rect x="0" y="0" width="160" height="160" rx="6" fill="#1a1a1a"/>` +
  layers +
  `</svg>`;

const out = join(here, 'gov-face-cycle.svg');
writeFileSync(out, svg);
console.log(`wrote ${out} (${svg.length} bytes, ${N} frames, ${TOTAL_S}s cycle)`);

// --- Also emit _gov-faces.ts into both server source trees ------------------
// Three string constants used by public-render.ts:
//   FACE_CYCLE    the multi-frame animated face (this file)
//   FACE_OK       static, used as the satisfied mark in rule lists
//   FACE_PENDING  static, used as the pending mark in rule lists
function fullSvg(file) {
  // Source SVGs already include xmlns + viewBox + width/height. We drop the
  // explicit width/height so they scale via CSS.
  return readFileSync(join(SRC, file), 'utf8')
    .replace(/\s*width="160"\s*height="160"/, '')
    .trim();
}

const FACE_OK_SVG = fullSvg('gov_18_pleased.svg');
const FACE_PENDING_SVG = fullSvg('gov_11_thinking.svg');
const CYCLE_FOR_INLINE = svg.replace(' width="160" height="160"', '');

const tsBody =
  '// Generated by brand/build-face-cycle.mjs. Do not edit by hand.\n' +
  '// Inline SVG strings for the gov face icons used by public-render.ts.\n' +
  '/* eslint-disable */\n' +
  `export const FACE_OK = ${JSON.stringify(FACE_OK_SVG)};\n` +
  `export const FACE_PENDING = ${JSON.stringify(FACE_PENDING_SVG)};\n` +
  `export const FACE_CYCLE = ${JSON.stringify(CYCLE_FOR_INLINE)};\n`;

const SERVERS = [
  join(here, '..', 'server', 'worker', 'src', '_gov-faces.ts'),
  join(here, '..', 'server', 'node', 'src', '_gov-faces.ts'),
];
for (const target of SERVERS) {
  writeFileSync(target, tsBody);
  console.log(`wrote ${target} (${tsBody.length} bytes)`);
}
